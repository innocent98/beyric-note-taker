"""Spike EX1: render a synthetic meeting (notes plus a transcript of N words) to PDF with
WeasyPrint and to Word with python-docx, and print wall time and peak memory of this process.

    python render.py WORDS [pdf|docx] [--no-fonts] [--repeat N]

The text is random words from a fixed list (seeded), laid out as "[Name]: ..." turns of 40 to 120
words, so the page count and the layout work are like a real transcript's.
"""

import random
import resource
import sys
import time
from html import escape
from pathlib import Path

WORDS = (
    "the project budget timeline client portal payment checkout design review launch release "
    "customer feedback priority risk blocker estimate sprint backlog update deadline Friday "
    "Monday decision approve schedule meeting notes action owner marketing engineering "
    "revenue forecast quarter hiring contract invoice vendor security privacy résumé café "
    "naïve Zoë Adeyemi Okafor Müller Dvořák we should need to think about whether and then "
    "because however actually basically maybe probably definitely next week this month"
).split()
NAMES = ["Adebayo", "Kemi Adeyemi", "Zoë Müller", "Daniel Okafor"]


def transcript(words: int) -> list[tuple[str, str]]:
    rng = random.Random(7)
    turns, used = [], 0
    while used < words:
        n = min(rng.randint(40, 120), words - used)
        text = " ".join(rng.choice(WORDS) for _ in range(n)).capitalize() + "."
        turns.append((rng.choice(NAMES), text))
        used += n
    return turns


NOTES = [
    ("Summary", ["The team reviewed the portal timeline and agreed the launch stays on 8 December."]),
    ("Key points", ["Checkout is the main blocker", "Marketing needs the final copy by Friday"] * 4),
    ("Decisions", ["Ship the portal on 8 December", "Hire one more engineer"]),
    ("Action items", ["Tosin: finish payment checkout (before Friday)", "Kemi: send the copy"]),
    ("Open questions", ["Who owns the invoice template?"]),
    ("Please check", ["Heard as Metrika; may be Metrica"]),
]

CSS = """
@page { size: A4; margin: 22mm 18mm 20mm;
  @bottom-left { content: "Generated by Beyric Note Taker, 3 Nov 2026"; font-size: 8pt; color: #666 }
  @bottom-right { content: counter(page) " / " counter(pages); font-size: 8pt; color: #666 } }
%FONTS%
body { font-family: %FAMILY%; font-size: 10.5pt; line-height: 1.5; color: #1a1a1a }
h1 { font-size: 20pt; margin: 0 0 4pt } h2 { font-size: 13pt; margin: 16pt 0 4pt; break-after: avoid }
.meta { color: #666; margin: 0 0 12pt } ul { padding-left: 16pt } li { margin: 2pt 0 }
.turn { margin: 0 0 6pt; break-inside: avoid } .who { font-weight: 600 }
"""


def html(turns, fonts: bool) -> str:
    font_css = (
        '@font-face { font-family: "Geist"; font-weight: 100 900; '
        'src: url("file:///fonts/geist-latin-wght-normal.woff2") }'
        if fonts
        else ""
    )
    css = CSS.replace("%FONTS%", font_css).replace(
        "%FAMILY%", '"Geist", sans-serif' if fonts else "sans-serif"
    )
    parts = [f"<html><head><meta charset=utf-8><style>{css}</style></head><body>"]
    parts.append("<h1>Portal planning</h1><p class=meta>3 Nov 2026 · Google Meet · 1 h</p>")
    for heading, items in NOTES:
        parts.append(f"<h2>{heading}</h2>")
        parts.append(
            "<p>" + escape(items[0]) + "</p>"
            if heading == "Summary"
            else "<ul>" + "".join(f"<li>{escape(i)}</li>" for i in items) + "</ul>"
        )
    if turns:
        parts.append("<h2>Transcript</h2>")
        for who, text in turns:
            parts.append(f'<p class=turn><span class=who>{escape(who)}:</span> {escape(text)}</p>')
    parts.append("</body></html>")
    return "".join(parts)


def docx(turns, path: str) -> int:
    from docx import Document

    doc = Document()
    doc.add_heading("Portal planning", 0)
    doc.add_paragraph("3 Nov 2026 · Google Meet · 1 h")
    for heading, items in NOTES:
        doc.add_heading(heading, 1)
        for item in items:
            doc.add_paragraph(item, style=None if heading == "Summary" else "List Bullet")
    if turns:
        doc.add_heading("Transcript", 1)
        for who, text in turns:
            p = doc.add_paragraph()
            p.add_run(f"{who}: ").bold = True
            p.add_run(text)
    doc.save(path)
    return Path(path).stat().st_size


def main() -> None:
    words = int(sys.argv[1])
    kind = sys.argv[2] if len(sys.argv) > 2 else "pdf"
    fonts = "--no-fonts" not in sys.argv
    turns = transcript(words)
    repeat = int(sys.argv[sys.argv.index("--repeat") + 1]) if "--repeat" in sys.argv else 1
    for run in range(1, repeat + 1):
        started = time.perf_counter()
        if kind == "pdf":
            from weasyprint import HTML

            document = HTML(string=html(turns, fonts)).render()
            pdf, pages = document.write_pdf(), len(document.pages)
            size = len(pdf)
            if "--save" in sys.argv:
                Path("/out/sample.pdf").write_bytes(pdf)
        else:
            size, pages = docx(turns, "/out/sample.docx" if "--save" in sys.argv else "/tmp/out.docx"), None
        took = time.perf_counter() - started
        peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024  # Linux: KiB
        print(f"{kind} words={words} fonts={fonts} run={run} seconds={took:.1f} "
              f"peak_mb={peak:.0f} bytes={size} pages={pages}")


main()
