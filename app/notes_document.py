"""`NotesDocument`: the one render model behind every export of a meeting's notes.

It is built once from the stored notes (and, when asked for, the transcript) and holds only
plain data: text runs, paragraphs, lists. PDF and Word render from it (`app/export_render.py`),
and the email layout of a later phase will too, so the formats cannot drift apart. Nothing in it
is HTML: each renderer escapes for its own format, so notes written by a model from untrusted
meeting text cannot inject markup into any of them.
"""

import re
import unicodedata
from datetime import UTC, datetime
from typing import Annotated, Literal
from urllib.parse import quote

from markdown_it import MarkdownIt
from markdown_it.token import Token
from pydantic import BaseModel, Field

MAX_FILENAME_CHARS = 100
FALLBACK_FILENAME = "meeting-notes"
# Characters that cannot go in a file name on some system, plus the ones that would break the
# Content-Disposition header. Control characters (line breaks included) are removed separately.
_FILENAME_BAD = re.compile(r'[/\\:*?"<>|]')

# The same parser settings as the page (`services.render_markdown`): CommonMark, no raw HTML, no
# linkify, no images. Tables and strikethrough stay off, so a stray pipe is just text.
_markdown = MarkdownIt("commonmark", {"html": False, "linkify": False}).disable("image")


class Run(BaseModel):
    text: str
    bold: bool = False
    italic: bool = False
    code: bool = False


class Paragraph(BaseModel):
    kind: Literal["paragraph"] = "paragraph"
    runs: list[Run]


class Heading(BaseModel):
    """A heading inside a section (`###` and below; `##` starts a new section)."""

    kind: Literal["heading"] = "heading"
    level: int
    runs: list[Run]


class CodeBlock(BaseModel):
    kind: Literal["code"] = "code"
    text: str


class Quote(BaseModel):
    kind: Literal["quote"] = "quote"
    blocks: list["Block"]


class ListBlock(BaseModel):
    kind: Literal["list"] = "list"
    ordered: bool
    start: int = 1
    # One entry per item; an item is the blocks inside it (a paragraph, then maybe a nested list).
    items: list[list["Block"]]


Block = Annotated[Paragraph | Heading | CodeBlock | Quote | ListBlock, Field(discriminator="kind")]
Quote.model_rebuild()
ListBlock.model_rebuild()


class Section(BaseModel):
    # None for text before the first `##` heading (the notes normally have none).
    heading: str | None
    blocks: list[Block]


class Turn(BaseModel):
    """One speaker turn. `speaker` is None for a transcript that carries no labels."""

    speaker: str | None
    text: str


class NotesDocument(BaseModel):
    title: str
    # "3 Nov 2026 · Google Meet · 1 h 12 min", the line under the title.
    meta: str
    sections: list[Section]
    transcript: list[Turn] | None = None
    # The footer line: "Generated by Beyric Note Taker, 3 Nov 2026".
    footer: str


# ---- notes (Markdown) to blocks ----


def _inline(token: Token) -> list[Run]:
    """The runs of one `inline` token. Links keep their text, and their address in brackets when
    it is a web address that the text does not already show."""
    runs: list[Run] = []
    bold = italic = 0
    links: list[tuple[str, int]] = []  # (address, index of the link's first run)

    def add(text: str, code: bool = False) -> None:
        if text:
            runs.append(Run(text=text, bold=bold > 0, italic=italic > 0, code=code))

    for child in token.children or []:
        match child.type:
            case "text":
                add(child.content)
            case "softbreak":
                add(" ")
            case "hardbreak":
                add("\n")
            case "code_inline":
                add(child.content, code=True)
            case "strong_open":
                bold += 1
            case "strong_close":
                bold -= 1
            case "em_open":
                italic += 1
            case "em_close":
                italic -= 1
            case "link_open":
                links.append((str(child.attrGet("href") or ""), len(runs)))
            case "link_close":
                href, first = links.pop() if links else ("", len(runs))
                shown = "".join(run.text for run in runs[first:])
                if re.match(r"https?://", href, re.IGNORECASE) and href != shown:
                    add(f" ({href})")
            case _:
                add(child.content)
    return runs


def _blocks(tokens: list[Token], start: int, stop: str | None) -> tuple[list[Block], int]:
    """Blocks from `tokens[start:]` up to the token type `stop` (exclusive); returns the blocks
    and the index of the token that ended them."""
    blocks: list[Block] = []
    i = start
    while i < len(tokens) and tokens[i].type != stop:
        token = tokens[i]
        match token.type:
            case "paragraph_open":
                blocks.append(Paragraph(runs=_inline(tokens[i + 1])))
                i += 3  # open, inline, close
            case "heading_open":
                level = int(token.tag[1:])
                blocks.append(Heading(level=level, runs=_inline(tokens[i + 1])))
                i += 3
            case "fence" | "code_block":
                blocks.append(CodeBlock(text=token.content.rstrip("\n")))
                i += 1
            case "blockquote_open":
                inner, i = _blocks(tokens, i + 1, "blockquote_close")
                blocks.append(Quote(blocks=inner))
                i += 1
            case "bullet_list_open" | "ordered_list_open":
                close = token.type.replace("_open", "_close")
                items: list[list[Block]] = []
                i += 1
                while tokens[i].type != close:
                    item, i = _blocks(tokens, i + 1, "list_item_close")
                    items.append(item)
                    i += 1
                ordered = token.type == "ordered_list_open"
                start_at = int(token.attrGet("start") or 1) if ordered else 1
                blocks.append(ListBlock(ordered=ordered, start=start_at, items=items))
                i += 1
            case _:  # hr, and anything else with no text of its own
                i += 1
    return blocks, i


def _plain(runs: list[Run]) -> str:
    return "".join(run.text for run in runs).strip()


def parse_sections(notes: str) -> list[Section]:
    """Split the notes at each top-level `##` heading. Anything before the first one is a section
    with no heading."""
    tokens = _markdown.parse(notes or "")
    sections: list[Section] = []
    heading: str | None = None
    pending: list[Token] = []

    def flush() -> None:
        blocks, _ = _blocks(pending, 0, None)
        if blocks or heading is not None:
            sections.append(Section(heading=heading, blocks=blocks))

    depth = 0
    i = 0
    while i < len(tokens):
        token = tokens[i]
        if depth == 0 and token.type == "heading_open" and token.tag == "h2":
            flush()
            pending = []
            heading = _plain(_inline(tokens[i + 1])) or None
            i += 3
            continue
        depth += token.nesting
        pending.append(token)
        i += 1
    flush()
    return sections


# ---- transcript ----

# `[Name]: words`, one line per turn, as the speaker step writes it (and `web/lib/transcript.ts`
# reads it). A line without a label continues the turn above it.
_LABELLED = re.compile(r"^\[([^\]\n]+)\]:\s?(.*)$")


def parse_transcript(text: str) -> list[Turn]:
    turns: list[Turn] = []
    labelled = False
    for raw in text.splitlines():
        match = _LABELLED.match(raw)
        if match:
            labelled = True
            turns.append(Turn(speaker=match.group(1).strip(), text=match.group(2).strip()))
        elif turns:
            turns[-1].text = f"{turns[-1].text}\n{raw.strip()}".strip()
        elif raw.strip():
            turns.append(Turn(speaker=None, text=raw.strip()))
    if not labelled:
        # No labels at all: paragraphs split at blank lines, not one block of the whole text.
        paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
        return [Turn(speaker=None, text=p) for p in paragraphs]
    return [t for t in turns if t.text or t.speaker]


# ---- the document ----


def _duration(seconds: int | None) -> str | None:
    if not seconds or seconds < 60:
        return None
    minutes = round(seconds / 60)
    hours, minutes = divmod(minutes, 60)
    if hours and minutes:
        return f"{hours} h {minutes} min"
    return f"{hours} h" if hours else f"{minutes} min"


def _date(when: datetime) -> str:
    when = when.astimezone(UTC)
    return f"{when.day} {when:%b %Y}"


def build_notes_document(
    *,
    title: str,
    platform_label: str,
    started_at: datetime,
    recorded_seconds: int | None,
    notes: str,
    transcript: str | None,
    generated_at: datetime,
) -> NotesDocument:
    """The document for one meeting. `transcript` is None when the owner did not ask for it."""
    meta = " · ".join(
        part for part in (_date(started_at), platform_label, _duration(recorded_seconds)) if part
    )
    return NotesDocument(
        title=title,
        meta=meta,
        sections=parse_sections(notes),
        transcript=parse_transcript(transcript) if transcript else None,
        footer=f"Generated by Beyric Note Taker, {_date(generated_at)}",
    )


# ---- file names ----


def export_filename(title: str, extension: str) -> str:
    """The title as a file name: path and header-breaking characters and control characters
    (line breaks included) removed, spaces collapsed, at most 100 characters, never empty."""
    cleaned = "".join(
        c
        for c in (" " if c.isspace() else c for c in title)
        if unicodedata.category(c) not in ("Cc", "Cf")
    )
    cleaned = _FILENAME_BAD.sub("", cleaned)
    cleaned = " ".join(cleaned.split()).strip(" .")
    cleaned = cleaned[:MAX_FILENAME_CHARS].strip(" .")
    return f"{cleaned or FALLBACK_FILENAME}.{extension}"


def content_disposition(filename: str) -> str:
    """An attachment header with an ASCII fallback and the real name as RFC 5987 `filename*`."""
    ascii_name = unicodedata.normalize("NFKD", filename).encode("ascii", "ignore").decode()
    extension = filename.rsplit(".", 1)[-1]
    stem = re.sub(r"[^A-Za-z0-9 ._()-]", "", ascii_name.removesuffix(f".{extension}")).strip()
    ascii_name = f"{stem or 'download'}.{extension}"
    return f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename, safe='')}"
