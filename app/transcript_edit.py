"""The transcript editor: rename a speaker, fix one line, move one line to another speaker.

What a person may change, and what they may never change:

* The transcript is one text, `[Name]: words` per turn. The page, Ask Beyric, the exports and the
  translations all read the same column, `speaker_transcript` and, when that is empty, `transcript`
  (`shown_text`). The edit changes THAT column and nothing else: `transcript` (the words the model
  heard) is left alone when the labelled copy is the one that is shown.
* A "line" is a row of the page: its 1-based position is what Ask Beyric cites and what a task or
  decision quote points at (`web/lib/transcript.ts`, `app/ask.py::transcript_rows`,
  `app/extraction.py::transcript_turns`: three copies of one split). So the number and order of
  rows NEVER change: no adding, deleting, splitting or merging. Every edit is checked afterwards
  (`_same_shape`): the same rows, in the same order, the same words and speakers in every row the
  edit did not name. An edit that would break that is refused and nothing is saved.
* Names go through `notes.clean_name`, the cleaning a participant's name gets, so a label can
  never carry `[`, `]`, `:` or a line break (`Bob]: injected` plus a line break and `[Admin`
  becomes `Bob injected Admin`).
  A line's text is one plain line: whitespace runs, line breaks and control characters become one
  space, so a typed line can never start a new row.
* The text as it was before the FIRST edit is kept once (`Meeting.transcript_original`), and
  `restore` puts it back. A two-person edit is caught by `version` (`transcript_text.version_of`,
  a hash of the shown text): an edit made from an older page is refused with 409
  `transcript_changed`.

Nothing is regenerated by an edit. The notes, the translations and the lists read from the notes
are then out of date, and the page says so (`notes_outdated`); the owner rewrites the notes when
they choose, which also reads the lists again.

Who may edit is the rule for deleting a meeting, `visibility.owns` (the recorder; for a meeting
owned by a team, its recorder while still a member, and the team's owner and admins), asked in
`editable_meeting`. Nothing here repeats it.
"""

import logging
import unicodedata
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import NoReturn

from fastapi import HTTPException
from sqlalchemy.exc import NoResultFound
from sqlalchemy.orm import Session

from app import notes, team_admin, visibility
from app.ask import _LABELLED
from app.extraction import transcript_turns
from app.models import Meeting, User
from app.services import Refused, _lock_meeting, visible_meeting_or_404
from app.transcript_text import version_of

logger = logging.getLogger(__name__)

MAX_LINE_CHARS = 5000  # one turn is a paragraph at most; a whole meeting in a line is not an edit
MAX_NAME_CHARS = notes.MAX_NAME_CHARS


# ---- the shown text ----


def shown_column(meeting: Meeting) -> str:
    """The column every reader shows: the labelled copy, else the plain one."""
    return "speaker_transcript" if meeting.speaker_transcript else "transcript"


def shown_text(meeting: Meeting) -> str:
    return meeting.speaker_transcript or meeting.transcript or ""


def is_edited(meeting: Meeting) -> bool:
    """A person has edited the transcript (and has not restored the original since)."""
    return meeting.transcript_original is not None


def notes_outdated(meeting: Meeting) -> bool:
    """The notes were written from different words than the page now shows. The notes remember the
    version of the text they came from (`notes_source_version`, set by a rewrite); with none, they
    came from the transcript as it was before any edit. So an edit makes them out of date, a
    rewrite makes them current, a second edit makes them out of date again, and restoring the
    original is current only if the notes were never rewritten from an edited text."""
    shown = shown_text(meeting)
    original = meeting.transcript_original if is_edited(meeting) else shown
    source = meeting.notes_source_version or version_of(original or "")
    return source != version_of(shown)


# ---- cleaning what a person typed ----


def clean_line(value: str) -> str:
    """One plain line: line breaks, whitespace runs and control characters become one space."""
    text = "".join(
        " " if c.isspace() or unicodedata.category(c) in ("Cc", "Zl", "Zp") else c
        for c in value
        if unicodedata.category(c) != "Cf"
    )
    return " ".join(text.split())


# ---- rows ----


@dataclass
class _Row:
    speaker: str | None
    start: int  # index of the row's first raw line
    end: int  # one past its last raw line


def _layout(lines: list[str]) -> list[_Row]:
    """Rows of the page, as raw-line ranges: a `[Name]:` line starts a row, any other line
    continues the one above (or starts a nameless first row). The split `transcript_rows` and
    `web/lib/transcript.ts` make."""
    rows: list[_Row] = []
    for index, raw in enumerate(lines):
        match = _LABELLED.match(raw)
        if match:
            if rows:
                rows[-1].end = index
            rows.append(_Row(match.group(1), index, len(lines)))
        elif not rows:
            rows.append(_Row(None, index, len(lines)))
    return rows


def speakers_of(text: str) -> list[str]:
    """Each speaker label once, in order of first speaking."""
    seen: list[str] = []
    for line in text.split("\n"):
        match = _LABELLED.match(line)
        if match and match.group(1) not in seen:
            seen.append(match.group(1))
    return seen


def _refuse(session: Session, status: int, code: str, message: str) -> NoReturn:
    session.rollback()  # ends the row lock
    raise Refused(status, code, message)


def _snapshot(text: str) -> list[tuple[str | None, str]]:
    return transcript_turns(text)


def _same_shape(before: str, after: str, expected: dict[int, tuple[str | None, str | None]]):
    """True when `after` has the rows of `before`: same count, and every row not in `expected`
    unchanged. `expected` maps a 1-based row to (speaker, text) it must now have; a None text
    means "unchanged"."""
    old, new = _snapshot(before), _snapshot(after)
    if len(old) != len(new):
        return False
    for number, ((old_who, old_text), (new_who, new_text)) in enumerate(
        zip(old, new, strict=True), start=1
    ):
        who, text = expected.get(number, (old_who, None))
        if new_who != who or new_text != (old_text if text is None else text):
            return False
    return True


def _need_names(session: Session, text: str) -> list[_Row]:
    lines = text.split("\n")
    rows = _layout(lines)
    if not any(row.speaker is not None for row in rows):
        _refuse(
            session,
            422,
            "no_speakers",
            "This transcript has no speaker names, so there is nothing to edit yet.",
        )
    return rows


def _relabel(raw: str, name: str) -> str:
    """`raw` (a `[Old]: words` line) with its label replaced; the rest of the line is kept."""
    match = _LABELLED.match(raw)
    assert match is not None
    return f"[{name}]" + raw[match.end(1) + 1 :]


# ---- the edits (pure on text; they refuse with `Refused` after rolling back) ----


def rename_speaker(session: Session, text: str, old: str, new: str, merge: bool) -> str:
    """Every line labelled exactly `old` is labelled `new`. When `new` is already a speaker of
    the meeting the two become one, and only with `merge`."""
    rows = _need_names(session, text)
    name = notes.clean_name(new)
    if not name:
        _refuse(session, 422, "invalid_name", "Type a name for this speaker.")
    present = speakers_of(text)
    if old not in present:
        _refuse(session, 422, "speaker_not_found", "No line is labelled with that speaker.")
    if name == old:
        _refuse(session, 422, "no_change", "That is already this speaker's name.")
    if name in present and not merge:
        _refuse(
            session,
            409,
            "speaker_exists",
            f"{name} is already a speaker in this meeting. Renaming would merge the two.",
        )
    lines = text.split("\n")
    expected: dict[int, tuple[str | None, str | None]] = {}
    for number, row in enumerate(rows, start=1):
        if row.speaker == old:
            lines[row.start] = _relabel(lines[row.start], name)
            expected[number] = (name, None)
    after = "\n".join(lines)
    if not _same_shape(text, after, expected):
        _refuse(session, 422, "invalid_edit", "That name cannot be saved.")
    return after


def edit_line(
    session: Session, text: str, line: int, new_text: str | None, new_speaker: str | None
) -> str:
    """Change one row's words, its speaker, or both. The rows stay where they are."""
    rows = _need_names(session, text)
    if not 1 <= line <= len(rows):
        _refuse(session, 422, "line_out_of_range", f"There is no line {line} in this transcript.")
    row = rows[line - 1]
    lines = text.split("\n")
    speaker = row.speaker
    if new_speaker is not None:
        speaker = notes.clean_name(new_speaker)
        if not speaker:
            _refuse(session, 422, "invalid_name", "Type a name for this speaker.")
    words = None
    if new_text is not None:
        words = clean_line(new_text)
        if not words:
            _refuse(session, 422, "empty_text", "A line cannot be empty.")
    old_words = _snapshot(text)[line - 1][1]
    if speaker == row.speaker and (words is None or words == clean_line(old_words)):
        _refuse(session, 422, "no_change", "Nothing changed on this line.")
    if words is not None:
        lines[row.start : row.end] = [f"[{speaker}]: {words}" if speaker else words]
    elif row.speaker is None:
        lines[row.start] = f"[{speaker}]: {lines[row.start]}"
    else:
        lines[row.start] = _relabel(lines[row.start], speaker)
    after = "\n".join(lines)
    if not _same_shape(text, after, {line: (speaker, words)}):
        _refuse(session, 422, "invalid_edit", "That text cannot be saved on this line.")
    return after


# ---- who and when ----


def editable_meeting(session: Session, user: User, meeting_id: int) -> Meeting:
    """The meeting, for a person who may change it. 404 when they may not even read it; 403
    `team_forbidden` (the code the team routes use for a reader who may not change) when they may
    read it (a teammate of a shared meeting, a member of a team's) but not change it. The rule is
    `visibility.owns`, the one a meeting's deletion asks (`services.owned_meeting_or_404`); only
    the answer for a reader differs: 403 here, as for moving a team's meeting back, because the
    page is told `can_edit_transcript` and a reader never sees the control."""
    meeting = visible_meeting_or_404(session, user, meeting_id)
    if not visibility.owns(session, user, meeting):
        raise team_admin.forbidden("Only the owner of this meeting can edit its transcript.")
    return meeting


def _locked_ready(session: Session, meeting: Meeting, version: str) -> tuple[Meeting, str]:
    try:
        locked = _lock_meeting(session, meeting)
    except NoResultFound:  # deleted between the read and the lock: the normal answer for a gone one
        session.rollback()
        raise HTTPException(404, "No such meeting") from None
    if locked.status != "ready":
        _refuse(
            session,
            409,
            "not_ready",
            "The transcript can be edited once the meeting is ready.",
        )
    text = shown_text(locked)
    if version != version_of(text):
        _refuse(
            session,
            409,
            "transcript_changed",
            "The transcript changed since you opened it. Reload the page and try again.",
        )
    return locked, text


def _save(user: User, meeting: Meeting, before: str, after: str) -> None:
    if meeting.transcript_original is None:
        meeting.transcript_original = before
    setattr(meeting, shown_column(meeting), after)
    meeting.transcript_edited_at = datetime.now(UTC)
    meeting.transcript_edited_by_user_id = user.id


def rename(
    session: Session, user: User, meeting: Meeting, version: str, old: str, new: str, merge: bool
) -> Meeting:
    locked, text = _locked_ready(session, meeting, version)
    after = rename_speaker(session, text, old, new, merge)
    _save(user, locked, text, after)
    session.commit()
    logger.info("meeting %s: transcript edit (rename a speaker)", locked.id)
    return locked


def change_line(
    session: Session,
    user: User,
    meeting: Meeting,
    version: str,
    line: int,
    text: str | None,
    speaker: str | None,
) -> Meeting:
    locked, shown = _locked_ready(session, meeting, version)
    after = edit_line(session, shown, line, text, speaker)
    _save(user, locked, shown, after)
    session.commit()
    logger.info("meeting %s: transcript edit (line %d)", locked.id, line)
    return locked


def restore(session: Session, meeting: Meeting, version: str) -> Meeting:
    """Put the text from before the first edit back, and forget the edit."""
    locked, _text = _locked_ready(session, meeting, version)
    if locked.transcript_original is None:
        _refuse(session, 409, "nothing_to_restore", "This transcript has not been edited.")
    setattr(locked, shown_column(locked), locked.transcript_original)
    locked.transcript_original = None
    locked.transcript_edited_at = None
    locked.transcript_edited_by_user_id = None
    session.commit()
    logger.info("meeting %s: transcript restored to the original", locked.id)
    return locked
