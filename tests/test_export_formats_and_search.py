def test_paging_with_a_search_follows_the_matches_only(api, session, template):
    hits = []
    for n in range(5):
        hits.append(ready(session, template, title=f"Budget {n}", notes="x").id)
        ready(session, template, title=f"Other {n}", notes="x")
    first = api.get("/api/meetings?q=budget&limit=2").json()
    assert [m["id"] for m in first["meetings"]] == hits[::-1][:2]
    assert first["has_more"] is True and first["next_before_id"] == hits[::-1][1]
    second = api.get(f"/api/meetings?q=budget&limit=2&before_id={first['next_before_id']}").json()
    third = api.get(f"/api/meetings?q=budget&limit=2&before_id={second['next_before_id']}").json()
    assert [m["id"] for m in second["meetings"]] == hits[::-1][2:4]
    assert [m["id"] for m in third["meetings"]] == hits[::-1][4:]
    assert third["has_more"] is False and third["next_before_id"] is None


