def test_markdown_is_the_notes_as_stored_under_a_title_and_date(api, session, template):
    meeting = ready(session, template, notes=RICH_NOTES, created_at=WHEN)
    response = export_of(api, meeting.id, format="md")
    assert response.status_code == 200
    assert response.headers["content-type"] == "text/markdown; charset=utf-8"
    assert response.headers["content-disposition"].startswith(
        'attachment; filename="Google Meet abc-defg-hij.md"'
    )
    assert response.headers["cache-control"] == "no-store"
    assert response.headers["x-content-type-options"] == "nosniff"
    body = response.text
    assert body.startswith("# Google Meet abc-defg-hij\n\n3 Nov 2026 · Google Meet\n\n")
    assert RICH_NOTES.strip() in body  # verbatim: marks, links and nesting untouched
    assert "## Transcript" not in body
    assert "\n\n*Generated by Beyric Note Taker, " in body and body.endswith("*\n")


