@pytest.mark.parametrize("fmt", ["md", "txt"])
def test_text_files_never_go_through_the_child_process_or_answer_busy(
    api, session, template, monkeypatch, fmt
):
    meeting = ready(session, template, notes=RICH_NOTES)

    def boom(*args, **kwargs):
        raise AssertionError("the renderer must not run for a text file")

    monkeypatch.setattr(export, "build_file", boom)
    assert export._one_at_a_time.acquire(blocking=False)  # a PDF build is "running"
    try:
        response = export_of(api, meeting.id, format=fmt)
    finally:
        export._one_at_a_time.release()
    assert response.status_code == 200, response.text


