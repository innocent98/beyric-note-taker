def found(handle, q, extra="", team=None):
    headers = {"X-Team-Id": str(team.id if hasattr(team, "id") else team)} if team else {}
    response = handle.client.get(f"/api/meetings?q={q}{extra}", headers=headers)
    assert response.status_code == 200, response.text
    return [m["id"] for m in response.json()["meetings"]]


