"""Tables in the document renderers (recipes plan T7): a draft's blocks become a `NotesDocument`
with real tables, rendered to PDF and Word through the same isolated child process as the notes.

The PDF tests need the Pango libraries (see `tests/test_export.py`): they skip without them unless
`CI` is set.
"""

import io
import os
from datetime import UTC, datetime

import pytest
from docx import Document as WordDocument

from app import export
from app.export_render import render_docx, render_html
from app.models import Document
from app.notes_document import Table, build_document_from_blocks
from app.recipes import blocks as b

try:
    import weasyprint  # noqa: F401

    HAVE_PANGO = True
except OSError:
    HAVE_PANGO = False

needs_pango = pytest.mark.skipif(
    not HAVE_PANGO and not os.environ.get("CI"), reason="the Pango libraries are not installed"
)

WHEN = datetime(2026, 11, 24, 9, 0, tzinfo=UTC)


def cell(text: str) -> b.Cell:
    return b.Cell(text=text)


def table(columns: list[str], rows: list[list[str]]) -> b.Table:
    return b.Table(columns=columns, rows=[[cell(t) for t in row] for row in rows])


def draft(blocks: list, title: str = "Proposal for Acme") -> Document:
    return Document(
        title=title,
        output_type="document",
        blocks=b.dump_blocks(blocks),
        created_at=WHEN,
    )


PRICES = table(["Item", "Price"], [["Setup", "₦450,000"], ["Support", "₦50,000"]])


def sample() -> Document:
    return draft(
        [
            b.Heading(level=1, text="Investment"),
            b.Paragraph(text="The costs we discussed."),
            PRICES,
            b.Heading(level=3, text="Notes"),
            b.Bullets(items=[b.Item(text="Paid monthly"), b.Item(text="[need: start date]")]),
        ]
    )


# ---- the render model ----


def test_blocks_become_sections_with_a_table_of_plain_text():
    out = build_document_from_blocks(sample())
    assert out.title == "Proposal for Acme"
    assert out.footer == "Generated by Beyric Note Taker, 24 Nov 2026"
    assert [s.heading for s in out.sections] == ["Investment"]
    kinds = [blk.kind for blk in out.sections[0].blocks]
    assert kinds == ["paragraph", "table", "heading", "list"]
    tbl = out.sections[0].blocks[1]
    assert isinstance(tbl, Table)
    assert tbl.columns == ["Item", "Price"]
    assert tbl.rows == [["Setup", "₦450,000"], ["Support", "₦50,000"]]


def test_text_before_the_first_heading_has_a_section_without_a_heading():
    out = build_document_from_blocks(draft([b.Paragraph(text="Hello"), PRICES]))
    assert [s.heading for s in out.sections] == [None]


def test_a_board_column_becomes_a_section_with_its_cards():
    column = b.Column(
        title="Decisions",
        cards=[b.Card(text="Ship on 8 December", kind="decision", owner="Ada")],
    )
    out = build_document_from_blocks(draft([column]))
    assert out.sections[0].heading == "Decisions"
    assert out.sections[0].blocks[0].kind == "list"


# ---- HTML (PDF) ----


def test_html_has_a_table_with_a_repeating_header_and_escaped_cells():
    hostile = draft(
        [table(["<b>Col</b>", "Price"], [["<script>alert(1)</script>", "a & b"]])],
        title="<i>Title</i>",
    )
    html = render_html(build_document_from_blocks(hostile))
    assert "<table" in html and "<thead>" in html and "<tbody>" in html
    assert "<script>" not in html
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in html
    assert "<th>&lt;b&gt;Col&lt;/b&gt;</th>" in html
    assert "a &amp; b" in html
    assert "<i>Title</i>" not in html


# ---- Word ----


def word_tables(content: bytes):
    return WordDocument(io.BytesIO(content)).tables


def test_docx_has_a_table_with_the_right_cell_text():
    content = render_docx(build_document_from_blocks(sample()))
    tables = word_tables(content)
    assert len(tables) == 1
    grid = [[c.text for c in row.cells] for row in tables[0].rows]
    assert grid == [["Item", "Price"], ["Setup", "₦450,000"], ["Support", "₦50,000"]]
    assert all(run.bold for run in tables[0].rows[0].cells[0].paragraphs[0].runs)


def test_docx_cell_with_markup_characters_is_kept_as_text():
    content = render_docx(
        build_document_from_blocks(draft([table(["A"], [["<w:p>&amp; =1+1</w:p>"]])]))
    )
    assert word_tables(content)[0].rows[1].cells[0].text == "<w:p>&amp; =1+1</w:p>"


def test_a_long_table_keeps_every_row_in_word():
    rows = [[f"Row {n}", str(n)] for n in range(150)]
    content = render_docx(build_document_from_blocks(draft([table(["Name", "No"], rows)])))
    assert len(word_tables(content)[0].rows) == 151


# ---- through the child process ----


def test_docx_goes_through_the_child_process():
    content = export.build_file(build_document_from_blocks(sample()), "docx")
    assert len(word_tables(content)) == 1


@needs_pango
def test_pdf_with_a_table_is_non_empty_through_the_child_process():
    doc = build_document_from_blocks(sample())
    content = export.build_file(doc, "pdf")
    assert content.startswith(b"%PDF") and len(content) > 1000


@needs_pango
def test_a_long_table_paginates_and_repeats_its_header_row():
    from weasyprint import HTML

    rows = [[f"Row {n}", f"₦{n * 1000:,}"] for n in range(120)]
    html = render_html(build_document_from_blocks(draft([table(["Name", "Price"], rows)])))
    page_count = len(HTML(string=html).render().pages)
    assert page_count >= 2
    assert "display: table-header-group" in render_html(build_document_from_blocks(sample()))


def test_the_child_process_environment_has_no_app_settings(monkeypatch):
    monkeypatch.setenv("OPENAI_API_KEY", "sk-secret-not-for-the-child")
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:pw@db/x")
    env = export._child_env()
    assert "OPENAI_API_KEY" not in env and "DATABASE_URL" not in env
