def test_every_writer_of_the_transcript_columns_is_known():
    """Prove none is missed (`grep`, kept as a test): a new assignment to `transcript` or
    `speaker_transcript` in `app/` or `scripts/` fails here until someone decides what it does to
    a transcript a person edited (`Meeting.transcript_original`)."""
    root = Path(__file__).resolve().parent.parent
    writes = re.compile(
        r"(?:meeting|locked|m)\.(?:speaker_)?transcript\s*=(?!=)|"
        r"setattr\(\s*\w+,\s*(?:shown_column|[^,]*transcript)"
    )
    found = {}
    for folder in ("app", "scripts"):
        for path in sorted((root / folder).rglob("*.py")):
            hits = [
                n for n, line in enumerate(path.read_text().splitlines(), 1) if writes.search(line)
            ]
            if hits:
                found[str(path.relative_to(root))] = len(hits)
    # Who writes a transcript, and why none of them can touch an edited one:
    #   app/pipeline.py: while a meeting is `processing`, before any edit is possible (an edit
    #     needs `ready`); `_step_speakers` also writes only when `speaker_transcript is None`.
    #   scripts/rebuild_meeting_from_evidence.py: refuses an edited meeting in `_check_state`.
    #   app/transcript_edit.py: the editor itself.
    #   scripts/capture_calendar_titles.py: makes fixture rows in a scratch database.
    assert found == {
        "app/pipeline.py": 5,
        "app/transcript_edit.py": 2,
        "scripts/capture_calendar_titles.py": 1,
        "scripts/rebuild_meeting_from_evidence.py": 4,
    }, found
