def test_renaming_a_speaker_changes_every_line_they_carry_and_nothing_else(api, session, template):
    meeting = meeting_of(session, template)
    response = rename(api, meeting, "Speaker 2", "Daniel")
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["transcript"] == LABELLED.replace("[Speaker 2]", "[Daniel]")
    assert body["participants"] == ["Ada", "Daniel"]
    row = stored(session, meeting)
    assert row.speaker_transcript == body["transcript"]
    assert row.transcript == PLAIN  # the model's own words are never touched
    assert row.transcript_original == LABELLED
    assert row.transcript_edited_by_user_id == meeting.owner_user_id
    assert row.transcript_edited_at is not None
    assert body["transcript_edited"] is True and body["transcript_edited_by"] == "owner"
    assert len(shape(row.speaker_transcript)) == len(shape(LABELLED)) == 4


