def test_the_rows_ask_cites_keep_their_numbers_after_every_kind_of_edit(api, session, template):
    meeting = meeting_of(session, template)
    before = ask.transcript_rows(LABELLED)
    for body in (
        {"rename": {"from": "Speaker 2", "to": "Daniel", "merge": False}},
        {"line": 3, "text": "Great, thanks."},
        {"line": 1, "speaker": "Daniel"},
    ):
        text = edit(api, meeting, body).json()["transcript"]
        rows = ask.transcript_rows(text)
        assert len(rows) == len(before) == 4
        assert [r.speaker for r in rows][3] == "Daniel"
    # the passages Ask reads carry the same row numbers, 1 to 4, in the same order
    passages = ask.transcript_rows(stored(session, meeting).speaker_transcript)
    assert [r.text for r in passages][1] == "I can ship it on Friday."


def test_a_quote_whose_line_was_fixed_loses_its_link_but_nothing_breaks(api, session, template):
    meeting = meeting_of(session, template)
    quote = "I can ship it on Friday"
    assert extraction.locate_quote(LABELLED, quote) == ("Speaker 2", 2)
    # a rename moves the quote's speaker with the row: still found, on the same row
    rename(api, meeting, "Speaker 2", "Daniel")
    text = stored(session, meeting).speaker_transcript
    assert extraction.locate_quote(text, quote) == ("Daniel", 2)
    assert ask._quote_row(quote, ask.transcript_rows(text)) == 2
    # the words fixed: the quote is no longer in the transcript, so there is no row to link to
    edit(api, meeting, {"line": 2, "text": "We will deliver on Thursday afternoon."})
    text = stored(session, meeting).speaker_transcript
    assert extraction.locate_quote(text, quote) is None
    assert ask._quote_row(quote, ask.transcript_rows(text)) is None  # Ask cites the notes instead
    assert detail(api, meeting)["transcript"] == text  # the page still loads


