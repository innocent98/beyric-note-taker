# ---- keep the original, restore it ----


def test_the_original_is_kept_once_and_restored_whole(api, session, template):
    meeting = meeting_of(session, template)
    rename(api, meeting, "Speaker 2", "Daniel")
    edit(api, meeting, {"line": 1, "text": "Hi all."})
    edit(api, meeting, {"line": 4, "speaker": "Ada"})
    assert stored(session, meeting).transcript_original == LABELLED  # the first, never a later one
    response = restore(api, meeting)
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["transcript"] == LABELLED
    assert (body["transcript_edited"], body["transcript_edited_at"]) == (False, None)
    assert body["transcript_edited_by"] is None
    row = stored(session, meeting)
    assert row.speaker_transcript == LABELLED and row.transcript == PLAIN
    assert (row.transcript_original, row.transcript_edited_at) == (None, None)
    assert row.transcript_edited_by_user_id is None
    error_of(restore(api, meeting), 409, "nothing_to_restore")
    # and a new edit after a restore keeps the new original
    rename(api, meeting, "Ada", "Ada Obi")
    assert stored(session, meeting).transcript_original == LABELLED


