PLAIN = "Hello everyone, thanks for joining. I can ship it on Friday. Great. Thanks."
LABELLED = "\n".join(
    [
        "[Ada]: Hello everyone, thanks for joining.",
        "[Speaker 2]: I can ship it on Friday.",
        "[Ada]: Great.",
        "That works for me.",
        "[Speaker 2]: Thanks.",
    ]
)


def meeting_of(session, template, **fields) -> Meeting:
    return ready(session, template, transcript=PLAIN, speaker_transcript=LABELLED, **fields)


def detail(handle, meeting) -> dict:
    return handle.get(f"/api/meetings/{meeting.id}").json()


def edit(handle, meeting, body, version=None):
    version = version or detail(handle, meeting)["transcript_version"]
    return handle.call(
        "PATCH", f"/api/meetings/{meeting.id}/transcript", {"version": version, **body}
    )


def rename(handle, meeting, old, new, merge=False, version=None):
    return edit(handle, meeting, {"rename": {"from": old, "to": new, "merge": merge}}, version)


def restore(handle, meeting, version=None):
    version = version or detail(handle, meeting)["transcript_version"]
    return handle.post(f"/api/meetings/{meeting.id}/transcript/restore", {"version": version})


def stored(session, meeting) -> Meeting:
    session.expire_all()
    return session.get(Meeting, meeting.id)


def shape(text: str) -> list[str | None]:
    """Who owns each row of the page, in order: what Ask and the quotes count by."""
    return [speaker for speaker, _words in extraction.transcript_turns(text)]


